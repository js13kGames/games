import fs from 'node:fs/promises'

import { CSP_EDITION } from '../config.js'

const API_ROOT = 'https://api.js13kgames.com'
const output = new URL('../csp.generated.ts', import.meta.url)

function slugify(value) {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[æ]/g, 'ae')
    .replace(/[\s:]/g, '-')
    .replace(/[^a-z0-9-]/g, '')
    .replace(/-{2,}/g, '-')
    .replace(/^-+|-+$/g, '')
}

function decodeGameSlugs(bytes) {
  const decoder = new TextDecoder()
  const slugs = []
  let offset = 0

  while (offset < bytes.length) {
    const categories = bytes[offset++]
    const titleLength = bytes[offset++]
    const title = decoder.decode(bytes.slice(offset, offset += titleLength))
    const authorLength = bytes[offset++]

    offset += authorLength

    if (categories) slugs.push(slugify(title))
  }

  return slugs
}

const editionIndex = CSP_EDITION - 2012
if (editionIndex < 0) throw new Error(`Invalid CSP edition: ${CSP_EDITION}`)

const response = await fetch(`${API_ROOT}/g:${editionIndex}`)
if (!response.ok) throw new Error(`Game index request failed: HTTP ${response.status}`)

const slugs = decodeGameSlugs(new Uint8Array(await response.arrayBuffer()))
if (!slugs.length) throw new Error(`Game index for ${CSP_EDITION} is empty`)

const source = [
  '// Generated by build/csp.js. Do not edit.',
  `export default new Set(${JSON.stringify(slugs, null, 2)})`,
  ''
].join('\n')

await fs.writeFile(output, source)
console.log(`Baked ${slugs.length} games for the ${CSP_EDITION} CSP reporting window`)
